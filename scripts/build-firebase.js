#!/usr/bin/env node
// Assembles the directory `firebase deploy` uploads for Hosting.
//
// Hosting serves a directory wholesale, and this repo's static files sit at
// the root next to service-account-key.json, data/*.db and .env — pointing
// Hosting at "." would publish all of it. So public/ is built from an
// explicit allowlist instead: anything not named here is never uploaded.
//
// The API does not run on Firebase (Cloud Functions needs the Blaze plan),
// so the browser calls it cross-origin. The base URL is injected as a
// generated js/config.js rather than edited into js/utils.js, because the
// same source also deploys to Vercel, where the API *is* same-origin and
// must keep using a relative base.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const CONFIG_PATH = path.join(ROOT, "hosting-config.json");

// Everything the browser is allowed to fetch. Keep in step with the src/href
// attributes in index.html and client-form.html.
const STATIC_ASSETS = ["index.html", "client-form.html", "styles.css", "js"];
const CONFIG_SCRIPT = '<script src="./js/config.js"></script>';
// config.js has to run before the code that reads window.MOTRACK_API_BASE:
// utils.js on the dashboard, and the single inline block on the client form,
// which carries its own copy of the fetch rather than sharing js/.
const HTML_PAGES = [
  { page: "index.html", anchor: '<script src="./js/utils.js"></script>' },
  { page: "client-form.html", anchor: "<script>" },
];

function apiBaseUrl() {
  if (process.env.API_BASE_URL) {
    return process.env.API_BASE_URL.trim();
  }
  if (!fs.existsSync(CONFIG_PATH)) {
    return "";
  }
  return String(JSON.parse(fs.readFileSync(CONFIG_PATH, "utf8")).apiBaseUrl || "").trim();
}

function writeConfig(baseUrl) {
  const body = [
    "// Generated by scripts/build-firebase.js — do not edit.",
    "// Read by getApiBaseUrl() in js/utils.js.",
    "window.MOTRACK_API_BASE = " + JSON.stringify(baseUrl) + ";",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(PUBLIC_DIR, "js", "config.js"), body);
}

// Injected into the copy under public/, never into the source page, so the
// Vercel deployment is untouched.
function injectConfigScript() {
  HTML_PAGES.forEach(({ page, anchor }) => {
    const file = path.join(PUBLIC_DIR, page);
    const html = fs.readFileSync(file, "utf8");
    if (!html.includes(anchor)) {
      throw new Error(page + ": could not find " + anchor + " to inject the config script before");
    }
    // String pattern, so only the first occurrence is replaced.
    fs.writeFileSync(file, html.replace(anchor, CONFIG_SCRIPT + "\n    " + anchor));
  });
}

function main() {
  fs.rmSync(PUBLIC_DIR, { recursive: true, force: true });
  fs.mkdirSync(PUBLIC_DIR, { recursive: true });

  const missing = [];
  STATIC_ASSETS.forEach((name) => {
    const source = path.join(ROOT, name);
    if (!fs.existsSync(source)) {
      missing.push(name);
      return;
    }
    fs.cpSync(source, path.join(PUBLIC_DIR, name), { recursive: true });
  });
  if (missing.length) {
    throw new Error("Missing static asset(s): " + missing.join(", "));
  }

  const baseUrl = apiBaseUrl();
  if (baseUrl) {
    writeConfig(baseUrl);
    injectConfigScript();
  }

  // A stray key inside the upload would be served as a static file, so fail
  // the build rather than deploy it.
  const leaked = ["service-account-key.json", ".env", ".env.local"].filter((name) =>
    fs.existsSync(path.join(PUBLIC_DIR, name))
  );
  if (leaked.length) {
    throw new Error("Refusing to deploy: " + leaked.join(", ") + " ended up in public/");
  }

  console.log("public/ <- " + STATIC_ASSETS.join(", "));
  console.log("API base: " + (baseUrl || "(same-origin)"));
}

main();
